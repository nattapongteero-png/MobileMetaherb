// Precomputed lowercase match terms per entry (title + aliases + keywords).
const MATCH_TERMS: { entry: HerbKBEntry; terms: string[] }[] = HERB_KB.map((e) => ({
  entry: e,
  terms: [e.title, ...e.aliases, ...e.keywords].map((t) => t.toLowerCase()),
}));

/**
 * Find KB entries relevant to a free-text query. Scores by term overlap:
 * an alias/title hit (the herb itself) weighs more than a keyword (a symptom),
 * so "อบเชยกินยังไง" surfaces cinnamon and "นอนไม่หลับ" surfaces the sleep herbs.
 * Returns [] when nothing meaningfully matches (caller falls back to web).
 */
export function searchHerbKB(query: string): HerbKBEntry[] {
  const q = query.toLowerCase().trim();
  if (!q) return [];
  const scored: { entry: HerbKBEntry; score: number }[] = [];
  for (const { entry, terms } of MATCH_TERMS) {
    let score = 0;
    // Herb-name / alias hit — the query names this herb directly.
    const nameTerms = [entry.title.toLowerCase(), ...entry.aliases.map((a) => a.toLowerCase())];
    for (const t of nameTerms) {
      if (t.length >= 2 && q.includes(t)) score += 5;
    }
    // Symptom / intent keyword hit.
    for (const k of entry.keywords) {
      const kl = k.toLowerCase();
      if (kl.length >= 2 && q.includes(kl)) score += 2;
    }
    if (score > 0) scored.push({ entry, score });
  }
  scored.sort((a, b) => b.score - a.score);
  return scored.slice(0, 3).map((s) => s.entry);
}

/** Look up a single entry by its stable id (e.g. to attach to a product). */
export function herbById(id: string): HerbKBEntry | undefined {
  return HERB_KB.find((e) => e.id === id);
}
